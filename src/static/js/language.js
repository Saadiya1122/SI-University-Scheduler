function getCurrentLanguage() {
    return localStorage.getItem("uniplan-language") || "en";
}

function getTranslation(text, language) {
    const dictionary = translations[language] || translations.en;
    return dictionary[text] ?? translations.en[text] ?? text;
}

function translateDynamicText(text, language) {
    if (language !== "de") return text;

    let translated = text;

    translated = translated.replace(/^(\d+)\s+professors?$/, "$1 Dozenten");
    translated = translated.replace(/^(\d+)\s+professor$/, "$1 Dozent");
    translated = translated.replace(/^(\d+)\s+sessions?$/, "$1 Veranstaltungen");
    translated = translated.replace(/^(\d+)\s+rooms?$/, "$1 Räume");
    translated = translated.replace(/^(\d+)\s+campuses?$/, "$1 Standorte");
    translated = translated.replace(/^(\d+)\s+Staff$/, "$1 Mitarbeitende");
    translated = translated.replace(/^(\d+)\s+seats$/, "$1 Sitzplätze");
    translated = translated.replace(/^(\d+)\s+students$/, "$1 Studierende");
    translated = translated.replace(/^(\d+)\s+hours?$/, "$1 Stunden");
    translated = translated.replace(/^Page\s+(\d+)\s+of\s+(\d+)$/, "Seite $1 von $2");
    translated = translated.replace(/^Faculty\s+(.+)$/, "Fakultät $1");
    translated = translated.replace(/^(\d+)\s+of\s+(\d+)\s+expected$/, "$1 von $2 erwartet");
    translated = translated.replace(/^\+\s*(\d+)\s+more\s+class$/, "+ $1 weitere Veranstaltung");
    translated = translated.replace(/^\+\s*(\d+)\s+more\s+classes$/, "+ $1 weitere Veranstaltungen");

    return translated;
}

function translateTextNode(textNode, language) {
    const original = textNode.nodeValue;
    const trimmed = original.trim();
    if (!trimmed) return;

    const parent = textNode.parentElement;
    if (!parent || parent.closest("script, style")) return;

    let translated = getTranslation(trimmed, language);
    translated = translateDynamicText(translated, language);

    if (translated !== trimmed) textNode.nodeValue = original.replace(trimmed, translated);
}

function translatePage(language) {
    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
    const nodes = [];
    let node;

    while (node = walker.nextNode()) nodes.push(node);
    nodes.forEach(textNode => translateTextNode(textNode, language));

    const dictionary = translations[language] || translations.en;

    document.querySelectorAll("input[placeholder]").forEach(input => {
        const placeholder = input.getAttribute("placeholder");
        const translated = dictionary[placeholder];
        if (translated !== undefined) input.setAttribute("placeholder", translated);
    });

    document.querySelectorAll("select option").forEach(option => {
        const text = option.textContent.trim();
        const translated = dictionary[text];
        if (translated !== undefined) option.textContent = translated;
    });
}

let languageObserverStarted = false;

function startLanguageObserver(language) {
    if (languageObserverStarted) return;
    languageObserverStarted = true;

    const observer = new MutationObserver(mutations => {
        mutations.forEach(mutation => {
            mutation.addedNodes.forEach(addedNode => {
                if (addedNode.nodeType === Node.TEXT_NODE) {
                    translateTextNode(addedNode, language);
                    return;
                }

                if (addedNode.nodeType !== Node.ELEMENT_NODE) return;

                const walker = document.createTreeWalker(addedNode, NodeFilter.SHOW_TEXT);
                const nodes = [];
                let node;

                while (node = walker.nextNode()) nodes.push(node);
                nodes.forEach(textNode => translateTextNode(textNode, language));
            });
        });
    });

    observer.observe(document.body, {
        childList:true,
        subtree:true
    });
}

